// snapshotGenerated records the content of every .md file under
// docs/arch/generated/, keyed by base name.
func snapshotGenerated(t *testing.T, root string) map[string]string {
	t.Helper()
	out := map[string]string{}
	for _, n := range listGenerated(t, root) {
		out[n] = readGenerated(t, root, n)
	}
	return out
}

// writeFile overwrites a repo-relative file with new content.
func writeFile(t *testing.T, root, rel, content string) {
	t.Helper()
	abs := filepath.Join(root, filepath.FromSlash(rel))
	require.NoError(t, os.WriteFile(abs, []byte(content), 0o644))
}

// firstLine returns the first line of s, for diagnostics.
func firstLine(s string) string {
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		return s[:i]
	}
	return s
}

// Test_gitDiffCleanAfterRegen exercises the CI invariant directly: in a
// git repo, `arch-gen` followed by `git diff --exit-code` over
// docs/arch/generated/ is clean on a second run.
func Test_gitDiffCleanAfterRegen(t *testing.T) {
	root := archtest.BuildRepo(t, archtest.SpecGenBasic())
	pkgs, inv, g, notes := genInputs(t, root)
	require.NoError(t, gen.Generate(root, pkgs, inv, g, notes), "first run")

	gitInit(t, root)

	// A second generation over identical inputs must leave git clean.
	require.NoError(t, gen.Generate(root, pkgs, inv, g, notes), "second run")
	out, err := gitDiff(root, "docs/arch/generated")
	require.NoError(t, err, "git diff: %s", out)
	require.Empty(t, strings.TrimSpace(out),
		"git diff --exit-code over docs/arch/generated must be clean after regen")
}

// gitInit initialises a git repo at root and commits everything, so a
// later git diff has a baseline to compare against.
func gitInit(t *testing.T, root string) {
	t.Helper()
	mustGit(t, root, "init", "-q")
	mustGit(t, root, "config", "user.email", "archgraph@test.local")
	mustGit(t, root, "config", "user.name", "archgraph test")
	mustGit(t, root, "add", "-A")
	mustGit(t, root, "commit", "-q", "-m", "baseline")
}

// mustGit runs a git subcommand at root and fails the test on error.
func mustGit(t *testing.T, root string, args ...string) {
	t.Helper()
	cmd := exec.Command("git", args...)
	cmd.Dir = root
	out, err := cmd.CombinedOutput()
	require.NoError(t, err, "git %s: %s", strings.Join(args, " "), out)
}

// gitDiff returns the output of `git diff -- <path>` at root.
func gitDiff(root string, path string) (string, error) {
	cmd := exec.Command("git", "diff", "--", path)
	cmd.Dir = root
	out, err := cmd.CombinedOutput()
	return string(out), err
}
