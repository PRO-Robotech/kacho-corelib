// Package gen implements archgraph's arch-gen pass: it generates the
// bottom two levels of the five-level architecture model — L3
// (per-functionality call-trees + reachable exported signatures) and L4
// (the application's exported domain types, fields and constants) — as
// deterministic, code-derived Markdown under docs/arch/generated/ of a
// service repository.
//
// # The five-level model
//
// L0–L2 are human-curated (the platform, the service and its
// functionalities); L3 and L4 are mechanical projections of the code, so
// archgraph generates them. A CI invariant — `make arch-gen` followed by
// `git diff --exit-code` — then catches any drift between the committed
// artifacts and the code they describe: the moment the code changes, a
// regenerated artifact differs and the diff is non-empty.
//
// # L3 — one artifact per L2 functionality note
//
// For every L2 note with a non-empty anchors list, Generate writes one
// docs/arch/generated/l3-<note-slug>.md. Its content is the union of the
// reachable-sets of the note's anchors:
//
//   - the call-tree — the deterministically sorted canonical names of
//     every function reachable from the functionality's entry-points;
//   - the exported signatures — for every reachable function that is an
//     exported function or method of *this* repository, its Go
//     signature as written in source.
//
// A planned functionality (empty anchors) has no reachable-set and
// therefore no L3 artifact.
//
// # L4 — one artifact per repository
//
// Generate writes a single docs/arch/generated/l4-<repo>.md tabulating
// the application's domain surface: every exported type of the
// repository's own packages (with its exported struct fields) and every
// exported package-level constant.
//
// # L4 scope — types, fields and constants
//
// L4 is deliberately scoped to exported types, their exported struct
// fields and exported package-level constants. Two further candidate
// tables — Postgres column inventories and configuration keys — were
// considered and left out: extracting them reliably needs domain
// knowledge of the ORM-less sqlc/pgx and viper/koanf conventions
// (struct-tag dialects, migration-file parsing) disproportionate to a
// generic, repository-agnostic generator. A repository that wants those
// tables can curate them in an L2 note. The scoping is fixed and the
// arch-gen acceptance fixture (scenario 4.0-D1) is shaped to match it.
//
// # Determinism and atomicity
//
// Every artifact is byte-for-byte reproducible: all collections are
// sorted by a stable key before rendering, never left in map-iteration
// or call-graph-traversal order. Each artifact is written atomically
// (temp file + rename in the destination directory), and an artifact
// left behind by a removed entry-point (an .md file under
// docs/arch/generated/ outside the set Generate is about to write) is
// deleted.
//
// Generate writes only under docs/arch/generated/; the curated L1/L2
// notes under docs/arch/ are never touched.
//
// This package depends only on the standard library, go/ast, go/types,
// golang.org/x/tools/go/packages and archgraph's own entrypoints, reach
// and note packages. It imports no gRPC runtime and no persistence code.
package gen

import (
	"fmt"
	"go/ast"
	"go/printer"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"

	"github.com/PRO-Robotech/kacho-corelib/internal/archgraph/entrypoints"
	"github.com/PRO-Robotech/kacho-corelib/internal/archgraph/note"
	"github.com/PRO-Robotech/kacho-corelib/internal/archgraph/reach"
)

// generatedSubdir is the docs/arch subdirectory arch-gen owns. Everything
// arch-gen writes lives here; nothing outside it is ever touched.
const generatedSubdir = "docs/arch/generated"

// genMarker is the header line every arch-gen artifact begins with. CI
// and human reviewers rely on it to tell a generated file from a curated
// one; it must never be edited by hand.
const genMarker = "<!-- GENERATED BY archgraph — DO NOT EDIT -->"

// Generate produces archgraph's L3 and L4 artifacts for the repository
// rooted at repoRoot and writes them under docs/arch/generated/.
//
// pkgs are the repository's loaded packages; inv its entry-point
// inventory; g the reachability graph reach.Compute already produced over
// pkgs and inv; notes its L2 functionality notes. The reachable-set
// keyed by an anchor's canonical symbol in g.Sets is what an L3
// artifact's call-tree and signatures are derived from.
//
// Generate creates docs/arch/generated/ if it is absent, writes one
// L3 artifact per anchored L2 note and one L4 artifact for the
// repository, and deletes any pre-existing .md file under
// docs/arch/generated/ that is not part of the freshly generated set
// (an artifact orphaned by a removed entry-point). Every write is
// atomic. Generate returns an error only on a filesystem failure.
func Generate(
	repoRoot string,
	pkgs []*packages.Package,
	inv *entrypoints.Inventory,
	g *reach.Graph,
	notes []*note.Note,
) error {
	outDir := filepath.Join(repoRoot, filepath.FromSlash(generatedSubdir))
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return fmt.Errorf("arch-gen: create %s: %w", generatedSubdir, err)
	}

	// Resolve every exported function/method of the repository to its
	// canonical SSA name, so a reachable-set member (an SSA name) can be
	// matched back to the AST declaration its signature is rendered from.
	exported := collectExportedFuncs(repoRoot, pkgs)
	names := resolveSSANames(pkgs, inv, exported)

	// repoPkgs is the set of import paths of the repository's own loaded
	// packages — the scope an L3 call-tree is restricted to. reach records
	// whole-program reachable-sets (RTA transitively descends into the
	// standard library and module-cache dependencies), so a raw call-tree
	// would dump the entire stdlib as documentation noise; an L3 artifact
	// must show only functions defined in *this* repository (the same
	// scoping C3's freshness hash applies to its file set).
	repoPkgs := collectRepoPkgPaths(pkgs)

	// artifacts is the set of file base names arch-gen is about to write —
	// the input to stale-removal.
	artifacts := map[string]struct{}{}

	// L3 — one artifact per anchored L2 functionality note.
	for _, n := range notes {
		if len(n.Anchors) == 0 {
			// A planned functionality has no reachable-set, hence no L3.
			continue
		}
		base := l3FileName(n)
		content := renderL3(n, g, exported, names, repoPkgs)
		if err := writeArtifact(outDir, base, content); err != nil {
			return err
		}
		artifacts[base] = struct{}{}
	}

	// L4 — a single per-repository domain-surface artifact.
	repo := repoName(repoRoot, pkgs)
	l4Base := "l4-" + repo + ".md"
	surface := collectDomainSurface(repoRoot, pkgs)
	if err := writeArtifact(outDir, l4Base, renderL4(repo, surface)); err != nil {
		return err
	}
	artifacts[l4Base] = struct{}{}

	// Stale removal: drop every .md under docs/arch/generated/ that the
	// run did not (re)write — an artifact orphaned by a removed
	// entry-point or a deleted note.
	return removeStale(outDir, artifacts)
}

// exportedFunc is one exported function or method of the repository: its
// declaration (for signature rendering), the file set that positions it,
// a human-readable name and the *types.Func behind it (the key into the
// SSA-name resolver).
type exportedFunc struct {
	obj      *ast.FuncDecl
	fset     *token.FileSet
	name     string
	typesObj *types.Func
}

// l3FileName returns the deterministic base name of a note's L3
// artifact: "l3-<note-slug>.md", where the slug is the note's file base
// name without its .md extension. The note path is the stable identity
// of a functionality, so the artifact name is reproducible across runs.
func l3FileName(n *note.Note) string {
	base := filepath.Base(n.Path())
	slug := strings.TrimSuffix(base, filepath.Ext(base))
	return "l3-" + slug + ".md"
}

// renderL3 builds the Markdown body of one L2 functionality's L3
// artifact: the GENERATED-BY marker, the functionality's anchors, the
// deterministically sorted call-tree of every reachable function and the
// Go signatures of the reachable functions that are exported symbols of
// this repository.
//
// repoPkgs scopes the call-tree: only functions defined in one of the
// repository's own packages are rendered. RTA's reachable-set spans the
// whole program — stdlib and module-cache dependencies included — so an
// unscoped call-tree would dump the entire Go standard library into the
// artifact (the defect the first real-repo roll-out exposed: a 1.4 MB
// L3 file). The reachable-set itself is left intact; only this document
// is scoped.
func renderL3(
	n *note.Note,
	g *reach.Graph,
	exported map[string]exportedFunc,
	names map[*ast.FuncDecl]string,
	repoPkgs map[string]struct{},
) string {
	var b strings.Builder
	b.WriteString(genMarker + "\n\n")
	fmt.Fprintf(&b, "# L3 — %s\n\n", strings.TrimSuffix(filepath.Base(n.Path()), ".md"))
	fmt.Fprintf(&b, "Generated from L2 note `%s`.\n\n", filepath.Base(n.Path()))

	// Anchors — the functionality's entry-points, sorted.
	anchors := anchorSymbols(n)
	b.WriteString("## Anchors\n\n")
	for _, a := range anchors {
		fmt.Fprintf(&b, "- `%s`\n", a)
	}
	b.WriteString("\n")

	// Call-tree — the union of the reachable-sets of every anchor, scoped
	// to functions defined in this repository (stdlib and dependency
	// functions RTA descended into are dropped from the document).
	funcs := reachableFuncs(n, g, repoPkgs)
	b.WriteString("## Call tree\n\n")
	if len(funcs) == 0 {
		b.WriteString("_No reachable functions._\n\n")
	} else {
		for _, f := range funcs {
			fmt.Fprintf(&b, "- `%s`\n", f)
		}
		b.WriteString("\n")
	}

	// Exported signatures — the reachable functions that are exported
	// symbols of this repository, rendered as their source signature.
	b.WriteString("## Exported signatures\n\n")
	sigs := reachableExportedSignatures(funcs, exported, names)
	if len(sigs) == 0 {
		b.WriteString("_No exported functions reachable._\n")
	} else {
		for _, s := range sigs {
			fmt.Fprintf(&b, "- `%s`\n", s)
		}
	}
	return b.String()
}

// anchorSymbols returns the canonical symbols of a note's anchors —
// gRPC method FQNs and worker type names — sorted and de-duplicated.
func anchorSymbols(n *note.Note) []string {
	set := map[string]struct{}{}
	for _, a := range n.Anchors {
		switch {
		case a.IsRPC():
			set[a.RPC] = struct{}{}
		case a.IsWorker():
			set[a.Worker] = struct{}{}
		}
	}
	return sortedKeys(set)
}

// reachableFuncs returns the deterministically sorted union of the
// reachable-set function names of every anchor of n, scoped to functions
// defined in one of the repository's own packages (repoPkgs). An anchor
// whose symbol is not a key of g.Sets (a stale anchor — C1's concern)
// contributes nothing.
//
// The scoping is the L3 counterpart of C3's repoRelPath file filter:
// reach records whole-program reachable-sets (RTA transitively descends
// into the standard library and module-cache dependencies), so an
// unscoped call-tree would render the entire Go standard library as
// documentation noise — the defect the first arch-gen roll-out on a real
// repository exposed (a single L3 artifact at ~1.4 MB / 21000+ lines).
// A reachable function whose canonical SSA name resolves to a package
// outside repoPkgs (a stdlib or dependency function) is dropped here;
// the underlying reachable-set is untouched, so C2's dead-code union
// still sees the full transitive closure.
func reachableFuncs(n *note.Note, g *reach.Graph, repoPkgs map[string]struct{}) []string {
	set := map[string]struct{}{}
	if g != nil {
		for _, sym := range anchorSymbols(n) {
			rs, ok := g.Sets[sym]
			if !ok {
				continue
			}
			for _, f := range rs.Funcs {
				if !isRepoFunc(f, repoPkgs) {
					continue
				}
				set[f] = struct{}{}
			}
		}
	}
	return sortedKeys(set)
}

// collectRepoPkgPaths returns the set of import paths of the
// repository's own loaded packages — the scope an L3 call-tree is
// restricted to. pkgs are the packages explicitly loaded for the
// repository ("./..."); their transitive imports — the standard library
// and module-cache dependencies — are deliberately excluded, which is
// exactly why a call-tree filtered through this set carries no stdlib
// noise. The main package is kept: a handler's own composition-root
// wiring is legitimate repository code.
func collectRepoPkgPaths(pkgs []*packages.Package) map[string]struct{} {
	out := map[string]struct{}{}
	for _, pkg := range pkgs {
		if pkg == nil || pkg.PkgPath == "" {
			continue
		}
		out[pkg.PkgPath] = struct{}{}
	}
	return out
}

// isRepoFunc reports whether a canonical SSA function name denotes a
// function defined in one of the repository's own packages (repoPkgs).
//
// A canonical SSA name is "pkg/path.Func" for a free function and
// "(*pkg/path.Type).Method" or "(pkg/path.Type).Method" for a method
// (reach derives it from *ssa.Function.String()). isRepoFunc strips any
// leading method-receiver decoration, then reports true iff some repo
// package path P is followed immediately by a "." — i.e. the symbol's
// defining package is P. A symbol whose package is the standard library
// or a module-cache dependency matches no repo path and is rejected,
// which is what keeps the L3 call-tree scoped to this repository.
func isRepoFunc(ssaName string, repoPkgs map[string]struct{}) bool {
	body := ssaName
	// Strip a method's "(*" / "(" receiver-open: the package path then
	// begins at the start of body, before the receiver type and ").".
	body = strings.TrimPrefix(body, "(*")
	body = strings.TrimPrefix(body, "(")
	for p := range repoPkgs {
		if strings.HasPrefix(body, p+".") {
			return true
		}
	}
	return false
}

// reachableExportedSignatures returns the sorted Go signatures of the
// reachable functions that are exported symbols of this repository. A
// reachable function whose SSA name matches no exported declaration (a
// private helper, a stdlib or dependency function) contributes no
// signature.
func reachableExportedSignatures(
	reachable []string,
	exported map[string]exportedFunc,
	names map[*ast.FuncDecl]string,
) []string {
	// Invert names: SSA canonical name -> declaration.
	bySSA := map[string]exportedFunc{}
	for _, ef := range exported {
		if ssa, ok := names[ef.obj]; ok {
			bySSA[ssa] = ef
		}
	}

	set := map[string]struct{}{}
	for _, ssa := range reachable {
		ef, ok := bySSA[ssa]
		if !ok {
			continue
		}
		set[renderSignature(ef)] = struct{}{}
	}
	return sortedKeys(set)
}

// renderSignature renders the Go signature of an exported function or
// method declaration as written in source: "func Name(params) results"
// for a free function, "func (recv) Name(params) results" for a method.
// The body is dropped. The declaration's *ast.FuncType prints as
// "func(params) results"; the function name is spliced in after the
// "func" keyword. printer output is canonical, so the rendering is
// deterministic across runs and checkouts.
func renderSignature(ef exportedFunc) string {
	fd := ef.obj
	funcType := printNode(ef.fset, fd.Type) // "func(params) results"
	signature := "func " + fd.Name.Name + strings.TrimPrefix(funcType, "func")

	if fd.Recv != nil && len(fd.Recv.List) > 0 {
		recv := printNode(ef.fset, fd.Recv.List[0].Type)
		return "func (" + recv + ") " + fd.Name.Name +
			strings.TrimPrefix(funcType, "func")
	}
	return signature
}

// printNode renders an AST node with go/printer, yielding canonical,
// deterministic Go source text.
func printNode(fset *token.FileSet, node ast.Node) string {
	var b strings.Builder
	cfg := printer.Config{Mode: printer.UseSpaces, Tabwidth: 4}
	if err := cfg.Fprint(&b, fset, node); err != nil {
		return ""
	}
	return b.String()
}

// repoName returns the last path segment of the repository's module
// path — the human-facing repository name used in the L4 artifact's file
// name and heading.
//
// The module path is taken, in order of preference, from a loaded
// package's Module record (populated only when packages.NeedModule was
// requested) or from the repository's go.mod. It falls back to "repo"
// when neither yields a module path.
func repoName(repoRoot string, pkgs []*packages.Package) string {
	mod := modulePath(pkgs)
	if mod == "" {
		mod = modulePathFromGoMod(repoRoot)
	}
	if mod == "" {
		return "repo"
	}
	if i := strings.LastIndex(mod, "/"); i >= 0 {
		return mod[i+1:]
	}
	return mod
}

// modulePath returns the module path of the analysed repository, read
// from any package's Module record. Every package of a single-module
// repository shares the same Module, so the first non-nil one is
// canonical. It returns "" when the packages were loaded without
// packages.NeedModule.
func modulePath(pkgs []*packages.Package) string {
	for _, p := range pkgs {
		if p.Module != nil && p.Module.Path != "" {
			return p.Module.Path
		}
	}
	return ""
}

// modulePathFromGoMod reads the module path from the "module" directive
// of the repository's go.mod. It is the load-mode-independent fallback
// for repoName: go.mod is always present in a Go module repository, so
// this resolves the name even when the packages were loaded without
// packages.NeedModule. An unreadable or directive-less go.mod yields "".
func modulePathFromGoMod(repoRoot string) string {
	data, err := os.ReadFile(filepath.Join(repoRoot, "go.mod"))
	if err != nil {
		return ""
	}
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if rest, ok := strings.CutPrefix(line, "module "); ok {
			return strings.TrimSpace(rest)
		}
	}
	return ""
}

// writeArtifact writes one artifact atomically into outDir: the content
// goes to a temp file in the same directory, which is then renamed over
// the destination, so a failure never leaves a half-written artifact and
// a concurrent reader sees either the old file or the new one.
//
// Every failure path — an unwritable directory, a write/sync/rename
// error — is reported with the single stable prefix "failed to write
// generated artifact: <dst>: <os error>", where <dst> is the
// artifact's destination path. arch-audit's CI-drift gate and the
// scenario-4.0-I5 read-only-directory test assert on that exact text,
// and the temp-file-plus-rename discipline guarantees a failed run
// leaves no artifact in a half-written state.
func writeArtifact(outDir, base, content string) error {
	dst := filepath.Join(outDir, base)
	// writeErr wraps any failure with the I5 stable prefix and the
	// destination path, so the error text never depends on which
	// internal step (temp-create, write, rename) failed.
	writeErr := func(err error) error {
		return fmt.Errorf("failed to write generated artifact: %s: %w", dst, err)
	}

	tmp, err := os.CreateTemp(outDir, ".archgraph-gen-*.tmp")
	if err != nil {
		return writeErr(err)
	}
	tmpName := tmp.Name()
	cleanup := func() {
		_ = tmp.Close()
		_ = os.Remove(tmpName)
	}
	if _, err := tmp.WriteString(content); err != nil {
		cleanup()
		return writeErr(err)
	}
	if err := tmp.Sync(); err != nil {
		cleanup()
		return writeErr(err)
	}
	if err := tmp.Chmod(0o644); err != nil {
		cleanup()
		return writeErr(err)
	}
	if err := tmp.Close(); err != nil {
		_ = os.Remove(tmpName)
		return writeErr(err)
	}
	if err := os.Rename(tmpName, dst); err != nil {
		_ = os.Remove(tmpName)
		return writeErr(err)
	}
	return nil
}

// removeStale deletes every .md file under outDir whose base name is not
// in keep — an artifact orphaned by a removed entry-point or a deleted
// L2 note. Non-".md" files and the temp files of a concurrent run are
// left alone.
func removeStale(outDir string, keep map[string]struct{}) error {
	entries, err := os.ReadDir(outDir)
	if err != nil {
		return fmt.Errorf("arch-gen: scan %s: %w", generatedSubdir, err)
	}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".md") {
			continue
		}
		if _, ok := keep[e.Name()]; ok {
			continue
		}
		if err := os.Remove(filepath.Join(outDir, e.Name())); err != nil {
			return fmt.Errorf("arch-gen: remove stale artifact %s: %w", e.Name(), err)
		}
	}
	return nil
}

// sortedKeys returns the keys of set as an ascending-sorted slice — the
// single choke-point that turns unordered map membership into the
// deterministic output every artifact depends on.
func sortedKeys(set map[string]struct{}) []string {
	out := make([]string, 0, len(set))
	for k := range set {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
